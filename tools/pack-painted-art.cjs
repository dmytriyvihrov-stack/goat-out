// Offline packaging only. Run with sharp available through NODE_PATH; the game has no dependency.
const fs = require('fs'), path = require('path'), sharp = require('sharp');
const root = path.resolve(__dirname, '..'), out = path.join(root, 'assets/painted');
const manifest = {};
async function pack(source, key, box, size, cutout) {
  const file = path.join(out, 'source', source + '.png');
  let pipeline = sharp(file).extract(box).ensureAlpha();
  let {data, info} = await pipeline.raw().toBuffer({resolveWithObject:true});
  const {width:w,height:h} = info;
  if (cutout) {
    // Some exported atlases bake their transparency preview into RGB. Treat its neutral,
    // bright matte as a color key, flood from outside and retain all enclosed artwork.
    const seen = new Uint8Array(w*h), queue = new Int32Array(w*h); let head=0,tail=0;
    const candidate = i => {
      const p=i*4, lo=Math.min(data[p],data[p+1],data[p+2]), hi=Math.max(data[p],data[p+1],data[p+2]);
      return data[p+3]<20 || (lo>138 && hi-lo<24);
    };
    const seed = i => {if(!seen[i]&&candidate(i)){seen[i]=1;queue[tail++]=i;}};
    for(let x=0;x<w;x++){seed(x);seed((h-1)*w+x);}
    for(let y=0;y<h;y++){seed(y*w);seed(y*w+w-1);}
    while(head<tail){const i=queue[head++],x=i%w,y=(i/w)|0;data[i*4+3]=0;
      if(x)seed(i-1);if(x<w-1)seed(i+1);if(y)seed(i-w);if(y<h-1)seed(i+w);}
    // Empty enclosed windows in the gong/table frame carry the same large matte clusters.
    for(let i=0;i<w*h;i++) if(!seen[i]&&candidate(i)) {
      const part=[], pending=[i];seen[i]=1;
      while(pending.length){const j=pending.pop();part.push(j);const x=j%w,y=(j/w)|0;
        for(const k of [x?j-1:-1,x<w-1?j+1:-1,y?j-w:-1,y<h-1?j+w:-1])
          if(k>=0&&!seen[k]&&candidate(k)){seen[k]=1;pending.push(k);}}
      if(part.length>80) for(const j of part)data[j*4+3]=0;
    }
    let x0=w,y0=h,x1=0,y1=0;
    for(let y=0;y<h;y++)for(let x=0;x<w;x++)if(data[(y*w+x)*4+3]>32){x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);}
    if(x1<=x0||y1<=y0)throw Error('Empty asset '+key);
    pipeline=sharp(data,{raw:{width:w,height:h,channels:4}}).extract({left:x0,top:y0,width:x1-x0+1,height:y1-y0+1});
  } else pipeline=sharp(data,{raw:{width:w,height:h,channels:4}});
  const buffer=await pipeline.resize({width:size,height:size,fit:'inside',kernel:'lanczos3'}).png().toBuffer();
  const m=await sharp(buffer).metadata();fs.writeFileSync(path.join(out,key+'.png'),buffer);
  manifest[key]={width:m.width,height:m.height,src:'data:image/png;base64,'+buffer.toString('base64')};
}
(async()=>{
  const columns=['sheep','clubman','mage','hound'];
  for(let row=0;row<2;row++)for(let col=0;col<4;col++){
    const left=Math.round(col*1774/4),top=Math.round(row*887/2);
    await pack('characters',columns[col]+(row?'Back':'Front'),{left,top,width:Math.round((col+1)*1774/4)-left,height:Math.round((row+1)*887/2)-top},192,true);
  }
  const props=[['crate',0,0,420,440],['brazier',460,0,340,440],['altar',800,0,540,440],['banner',1340,0,434,440],
    ['barrel',0,443,443,444],['lamp',444,443,400,444],['hay',844,443,490,444],['gong',1334,443,440,444]];
  for(const [key,left,top,width,height]of props)await pack('objects',key,{left,top,width,height},key==='altar'?384:192,true);
  const tiles=['stone0','stone1','stone2','stone3','wallTop','wallFace','boards0','boards1'];
  for(let i=0;i<8;i++){const col=i%4,row=(i/4)|0,left=Math.round(col*1774/4),top=Math.round(row*887/2);
    await pack('tiles',tiles[i],{left,top,width:Math.round((col+1)*1774/4)-left,height:Math.round((row+1)*887/2)-top},128,false);}
  fs.writeFileSync(path.join(root,'js/painted-assets.js'),'// Generated by tools/pack-painted-art.cjs. Embedded so file:// and artifact builds work offline.\nconst PAINTED_ASSETS = '+JSON.stringify(manifest)+';\n');
  console.log('Packed',Object.keys(manifest).length,'assets;',fs.statSync(path.join(root,'js/painted-assets.js')).size,'bytes embedded.');
})().catch(e=>{console.error(e);process.exitCode=1;});
