// Offline packaging only, no sharp needed: the source PNGs in assets/painted-expansion-v1/ are
// already cropped, padded and sheet-packed by that package's own pack.cjs. This script only
// base64-embeds the finished sheets so file:// and artifact builds work offline, the same way
// tools/pack-painted-art.cjs embeds assets/painted/.
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..'), src = path.join(root, 'assets/painted-expansion-v1');
const manifest = {};
function embed(key, relPath) {
  const buffer = fs.readFileSync(path.join(src, relPath));
  // PNG dimensions sit at fixed offsets in the IHDR chunk (bytes 16-23), no decode needed.
  const width = buffer.readUInt32BE(16), height = buffer.readUInt32BE(20);
  manifest[key] = { width, height, src: 'data:image/png;base64,' + buffer.toString('base64') };
}
embed('sheepWalk', 'units/sheep-walk.png');
embed('clubmanWalk', 'units/clubman-walk.png');
embed('mageWalk', 'units/mage-walk.png');
embed('houndWalk', 'units/hound-walk.png');
embed('brazierFire', 'effects/brazier-fire.png');
embed('torchFire', 'effects/torch-fire.png');
embed('lanternFire', 'effects/lantern-fire.png');
embed('doorWood', 'doors/wood.png');
embed('doorIron', 'doors/iron.png');
embed('doorVault', 'doors/vault.png');
embed('doorSoul', 'doors/soul.png');
embed('propsAtlas', 'objects/atlas.png');
const out = path.join(root, 'js/painted-assets-v1.js');
fs.writeFileSync(out, '// Generated by tools/pack-painted-expansion.cjs from assets/painted-expansion-v1/. Embedded so file:// and artifact builds work offline.\nconst PAINTED_ASSETS_V1 = ' + JSON.stringify(manifest) + ';\n');
console.log('Packed', Object.keys(manifest).length, 'assets;', fs.statSync(out).size, 'bytes embedded.');
