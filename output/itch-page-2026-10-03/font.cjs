// Lays a string out as a mask: { w, h, on(x, y) } in font pixels times k.
function layout(font, s, k = 1, gap = 1) {
  const glyphs = [...s.toUpperCase()].map((ch) => font[ch] || font[' ']);
  const h = glyphs[0].length, w = glyphs.reduce((a, g) => a + g[0].length + gap, -gap);
  const bits = new Uint8Array(w * h);
  let x0 = 0;
  for (const g of glyphs) { for (let j = 0; j < h; j++) for (let i = 0; i < g[j].length; i++) if (g[j][i] === '#') bits[j * w + x0 + i] = 1; x0 += g[0].length + gap; }
  return { w: w * k, h: h * k, on: (x, y) => x >= 0 && y >= 0 && x < w * k && y < h * k && bits[Math.floor(y / k) * w + Math.floor(x / k)] === 1 };
}

